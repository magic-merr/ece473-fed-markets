"""Liquidity of the index legs, 90-day vs 60-day horizon (TASKS 4). Palmer.

For every index day from 2023-02-02 and each leg the index uses (near meeting m1, far meeting m2, at the cut
strike U - 0.25 and the hike strike U), from the committed Kalshi candles via index/legs.py:
  spread        standing ask - bid when the book is two-sided
  traded        any volume that day
  price source  quote / bound / trade / tail fill / stale under the src rule (decision 002)
Legs with zero weight that day are skipped. Days at the zero lower bound are skipped for the cut leg.

Run: cd src && python leg_liquidity.py  ->  results/leg_liquidity.md
"""
from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "index"))

import build  # noqa: E402
import legs  # noqa: E402

OUT = ROOT / "results"


def leg_days() -> pd.DataFrame:
    cd = legs.contract_days("src")
    cd = cd.set_index(["meeting", "strike", "date"]).sort_index()
    rows = []
    for h in (90, 60):
        for d in pd.date_range(build.SAMPLE_START, legs.data_end(), freq="D").date:
            br = build.bracket(d, h)
            if br is None:
                continue
            m1, m2, w = br
            u = build.ub_at(d)
            for side, k in (("cut", build.cut_strike(u)), ("hike", build.hike_strike(u))):
                if side == "cut" and u <= 0.25:
                    continue
                for role, m, wt in (("near", m1, w), ("far", m2, 1 - w)):
                    if wt <= 0:
                        continue
                    key = (m, round(k, 4), d)
                    r = cd.loc[key] if key in cd.index else None
                    if r is None or isinstance(r, pd.DataFrame):
                        r = r.iloc[0] if isinstance(r, pd.DataFrame) else None
                    two = r is not None and r["bid"] > 0 and r["ask"] < 1
                    rows.append({"horizon": h, "side": side, "role": role, "date": d,
                                 "days_to_meeting": (m - d).days, "weight": wt,
                                 "listed": r is not None, "two_sided": bool(two),
                                 "spread": (r["ask"] - r["bid"]) if two else np.nan,
                                 "traded": bool(r is not None and r["volume"] > 0),
                                 "source": r["source"] if r is not None else "not_listed"})
    return pd.DataFrame(rows)


def table(x: pd.DataFrame, keys) -> pd.DataFrame:
    g = x.groupby(keys)
    t = g.agg(leg_days=("date", "size"), median_days_to_meeting=("days_to_meeting", "median"),
              share_two_sided=("two_sided", "mean"), median_spread_c=("spread", lambda s: 100 * s.median()),
              p90_spread_c=("spread", lambda s: 100 * s.quantile(0.9)), share_traded=("traded", "mean"))
    src = pd.crosstab([x[k] for k in keys], x["source"], normalize="index")
    for c in ("quote", "bound", "trade", "tailfill", "stale", "not_listed"):
        t[f"share_{c}"] = src[c] if c in src else 0.0
    return t.reset_index()


def main():
    x = leg_days()
    pooled = table(x, ["horizon", "role"])
    by_side = table(x, ["horizon", "side", "role"])
    md = lambda d: d.to_markdown(index=False, floatfmt=".2f")  # noqa: E731
    lines = ["# Index leg liquidity: 90-day vs 60-day horizon (TASKS 4)", "",
             f"Generated by `src/leg_liquidity.py` on {dt.date.today()}. Index days from {build.SAMPLE_START} to "
             f"{legs.data_end()}, committed Kalshi candles, src price rule. One row per index day and leg; "
             "spreads in cents, on two-sided books only. share_trade: priced by the last-trade branch (a book "
             "wider than 10c or one-sided); share_stale: no usable price.", "",
             "## Pooled over CUT and HIKE", "", md(pooled), "", "## By side", "", md(by_side), ""]
    OUT.mkdir(exist_ok=True)
    (OUT / "leg_liquidity.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
